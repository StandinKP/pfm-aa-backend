/**
 * MOCK enclave — what the PFM workload will do with a schema-2 job once the
 * platform's verifier (ADR-004 Phase 4) and in-enclave AA fetch land, written
 * to the order in patternc-kit/docs/FIU-REBUILD-VC.md §3 and the error names in
 * issuer/tests/fixtures/corpus/MANIFEST.json. It exists so the app, the
 * presentation builder and the sealed-reply path can be built and tested while
 * Airlock/Octic and the real enclave are built in parallel.
 *
 * It is NOT the real verifier: one in-memory trust anchor instead of a signed
 * bundle, no revocation/status lists, no role checks, no provenance. A green
 * run here proves the app speaks the profile; it proves nothing about the
 * enclave. The "AA fetch" returns a document generated by the real PFM worker
 * (rules-local decider) from synthetic records — see fixtures/.
 */
import { CompactEncrypt, compactVerify, decodeJwt, importJWK, type JWK } from "jose";
import { fromUtf8, utf8 } from "../lib/bytes";
import { didKeyFromP256Jwk, type P256PublicJwk } from "../lib/didkey";
import { thumbprint } from "../lib/keys";
import { MAX_LIFETIME_SECONDS, VC_PROFILE, payloadDigest } from "../vc/present";
import fixture from "./fixtures/insights-customer-test-001.json";

export class EnclaveRefusal extends Error {
  constructor(readonly errorType: string) {
    super(errorType);
  }
}

export interface MockTrust {
  issuerJwk: P256PublicJwk;
  workloadAudience: string;
  /** jti values already seen — presentations are single use. */
  seen: Set<string>;
}

const refuse = (t: string): never => {
  throw new EnclaveRefusal(t);
};

async function verifyCompact(jws: string, jwk: JWK, on: string): Promise<Record<string, unknown>> {
  try {
    const { payload } = await compactVerify(jws, await importJWK(jwk, "ES256"));
    return JSON.parse(fromUtf8(payload)) as Record<string, unknown>;
  } catch {
    return refuse(on);
  }
}

export interface Scope {
  customerId: string;
  consentId: string;
  accountLabels: string[];
}

export async function verifyJob(body: Record<string, unknown>, jobId: string, trust: MockTrust, now = Math.floor(Date.now() / 1000)): Promise<Scope> {
  if (body["schema"] !== "urn:sahamati:cs-job:2" || typeof body["vp"] !== "string") refuse("PresentationInvalidError");
  if ("consent" in body) refuse("PresentationInvalidError"); // scope comes from the credential, never a typed field
  const vpJws = body["vp"] as string;

  // 1. Pull the credentials out of the (not yet trusted) presentation.
  let claims: Record<string, any>;
  try {
    claims = decodeJwt(vpJws) as Record<string, any>;
  } catch {
    return refuse("PresentationInvalidError");
  }
  const envelopes: Array<{ id?: string }> = claims["vp"]?.verifiableCredential ?? [];
  const jwts = envelopes.map((e) => String(e.id ?? "").replace(/^data:application\/vc\+jwt,/, ""));
  if (jwts.length !== 2) refuse("PresentationInvalidError");

  // 2. Agent credential: issuer signature, validity, and the holder key it carries.
  const agent = await verifyCompact(jwts[0]!, trust.issuerJwk, "PresentationInvalidError");
  const holderJwk = (agent["cnf"] as { jwk?: P256PublicJwk } | undefined)?.jwk;
  if (!(Number(agent["exp"]) > now)) refuse("PresentationInvalidError");
  if (!holderJwk || didKeyFromP256Jwk(holderJwk) !== claims["iss"]) refuse("PresentationInvalidError");

  // 3. Presentation: signature under that key, then claims.
  const vp = await verifyCompact(vpJws, holderJwk as JWK, "PresentationInvalidError");
  if (vp["profile"] !== VC_PROFILE) refuse("PresentationInvalidError");
  if (vp["aud"] !== trust.workloadAudience) refuse("PresentationAudienceError");
  const { iat, exp } = vp as { iat: number; exp: number };
  if (!(exp > now)) refuse("PresentationExpiredError");
  if (exp - iat > MAX_LIFETIME_SECONDS) refuse("PresentationInvalidError");
  if (vp["jobId"] !== jobId) refuse("PresentationInvalidError");
  if (trust.seen.has(String(vp["jti"]))) refuse("PresentationInvalidError");
  if (vp["payloadDigest"] !== (await payloadDigest(body))) refuse("PayloadDigestMismatchError");
  trust.seen.add(String(vp["jti"]));

  // 4. Consent credential: issuer signature, validity, binding to the presenter.
  const consent = await verifyCompact(jwts[1]!, trust.issuerJwk, "IssuerKeyUnauthorisedError");
  if (!(Number(consent["exp"]) > now)) refuse("ConsentVcExpiredError");
  const s = (consent["credentialSubject"] ?? {}) as Record<string, any>;
  if (s["id"] !== vp["iss"]) refuse("PresentationInvalidError");

  return { customerId: String(s["customerId"]), consentId: String(s["consentId"]), accountLabels: s["accountLabels"] as string[] };
}

/** Process a verified job: scope check, "fetch" from the mock AA, seal to `replyTo`. Returns the reply `output` string. */
export async function processJob(body: Record<string, unknown>, scope: Scope): Promise<string> {
  const need = new Set(fixture.accounts as string[]);
  if (![...need].every((a) => scope.accountLabels.includes(a))) refuse("ConsentRejectedError"); // reject, never trim

  const replyTo = body["replyTo"] as P256PublicJwk | undefined;
  if (!replyTo || replyTo.kty !== "EC" || replyTo.crv !== "P-256" || "d" in (replyTo as object)) refuse("ReplyKeyMissingError");
  const key = await importJWK(replyTo as JWK, "ECDH-ES");
  const sealed = await new CompactEncrypt(utf8(JSON.stringify(fixture)))
    .setProtectedHeader({ alg: "ECDH-ES", enc: "A256GCM", kid: await thumbprint(replyTo as P256PublicJwk), cty: fixture.schema })
    .encrypt(key);

  const meta = { recordsIn: fixture.recordsIn, accounts: fixture.accounts.length, decider: { backend: "mock-enclave", version: "0" }, taxonomyVersion: (fixture as { taxonomy?: string }).taxonomy ?? null };
  return JSON.stringify({ schema: "urn:sahamati:pfm-reply:1", meta, sealed, provenance: null });
}
