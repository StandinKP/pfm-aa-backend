import { expect, test } from "bun:test";
import { generateKeyPairSync } from "node:crypto";
import { existsSync, readFileSync } from "node:fs";
import { open, privateKeyFromPem, seal } from "../src/hpke";

const info = new TextEncoder().encode("airlock.reply.v1|abc|sha256:def");

test("seal/open round trip, and a wrong info fails", () => {
  const r = generateKeyPairSync("x25519");
  const raw = Buffer.from(r.publicKey.export({ format: "jwk" }).x!, "base64url");
  const s = seal({ recipientPublicRaw: raw, info, pt: Buffer.from("hi"), ephemeral: generateKeyPairSync("x25519") });
  expect(open({ recipientKey: r.privateKey, enc: s.enc, ct: s.ct, info }).toString()).toBe("hi");
  expect(() => open({ recipientKey: r.privateKey, enc: s.enc, ct: s.ct, info: new TextEncoder().encode("x") })).toThrow();
});

// Independent implementation: a blob sealed by Python `cryptography` (hpke module). Generated by tests/fixtures/make-hpke-vector.py.
test("opens a blob sealed by Python cryptography", () => {
  const f = new URL("./fixtures/hpke-python.json", import.meta.url);
  if (!existsSync(f)) return;
  const v = JSON.parse(readFileSync(f, "utf8")); // synthetic throwaway key
  const blob = Buffer.from(v.blob, "base64");
  const pt = open({ recipientKey: privateKeyFromPem(v.pem), enc: blob.subarray(0, 32), ct: blob.subarray(32), info: new TextEncoder().encode(v.info) });
  expect(pt.toString()).toBe('{"hello":"world"}');
});
